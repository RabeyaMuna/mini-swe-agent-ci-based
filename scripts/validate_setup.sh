#!/bin/bash
# validate_setup.sh
# Validates that the system is properly configured and ready to run

set -e

echo "================================================================================"
echo "CI Memory System - Setup Validation"
echo "================================================================================"
echo ""

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

SUCCESS=0
WARNINGS=0
ERRORS=0

# Function to check command
check_command() {
    if command -v $1 &> /dev/null; then
        echo -e "${GREEN}✓${NC} $1 is installed"
        return 0
    else
        echo -e "${RED}✗${NC} $1 is NOT installed"
        ((ERRORS++))
        return 1
    fi
}

# Function to check Python package
check_python_package() {
    if python3 -c "import $1" 2>/dev/null; then
        echo -e "${GREEN}✓${NC} Python package '$1' is installed"
        return 0
    else
        echo -e "${RED}✗${NC} Python package '$1' is NOT installed"
        ((ERRORS++))
        return 1
    fi
}

# Function to check environment variable
check_env_var() {
    if [ -z "${!1}" ]; then
        echo -e "${YELLOW}⚠${NC} Environment variable $1 is NOT set"
        ((WARNINGS++))
        return 1
    else
        echo -e "${GREEN}✓${NC} Environment variable $1 is set"
        return 0
    fi
}

# Function to check file exists
check_file() {
    if [ -f "$1" ]; then
        echo -e "${GREEN}✓${NC} File exists: $1"
        return 0
    else
        echo -e "${YELLOW}⚠${NC} File not found: $1"
        ((WARNINGS++))
        return 1
    fi
}

# Function to check directory
check_directory() {
    if [ -d "$1" ]; then
        echo -e "${GREEN}✓${NC} Directory exists: $1"
        return 0
    else
        echo -e "${YELLOW}⚠${NC} Directory not found: $1 (will be created)"
        ((WARNINGS++))
        return 1
    fi
}

echo "1. SYSTEM REQUIREMENTS"
echo "----------------------"
check_command python3
check_command pip3 || check_command pip
check_command jq
echo ""

echo "2. PYTHON PACKAGES"
echo "------------------"
check_python_package datasets
check_python_package litellm
check_python_package sentence_transformers
check_python_package sklearn
check_python_package typer
check_python_package rich
check_python_package numpy
echo ""

echo "3. ENVIRONMENT VARIABLES (Optional but Recommended)"
echo "---------------------------------------------------"
check_env_var OPENROUTER_API_KEY
check_env_var OPENROUTER_BASE_URL
if [ -z "$OPENROUTER_API_KEY" ]; then
    echo "   Note: You can also use MINIMAX_API_KEY + MINIMAX_BASE_URL"
    check_env_var MINIMAX_API_KEY
    check_env_var MINIMAX_BASE_URL
fi
echo ""

echo "4. REQUIRED SCRIPTS"
echo "-------------------"
check_file "scripts/decompose_ci_failure.py"
check_file "scripts/prepare_memory_train_test_split.py"
check_file "scripts/run_complete_workflow.sh"
echo ""

echo "5. DIRECTORIES"
echo "--------------"
check_directory "data/trs"
check_directory "scripts"
echo ""

echo "6. OPTIONAL FILES (Generated by workflow)"
echo "-----------------------------------------"
check_file "data/trs/filtered_issues.jsonl"
check_file "data/trs/decomposed_issues.json"
check_file "data/trs/memory_set.jsonl"
check_file "data/trs/failure_memory.json"
check_file "data/trs/repo_memory.json"
check_file "data/trs/cross_memory.json"
echo ""

# Summary
echo "================================================================================"
echo "VALIDATION SUMMARY"
echo "================================================================================"
echo ""

if [ $ERRORS -eq 0 ] && [ $WARNINGS -eq 0 ]; then
    echo -e "${GREEN}✓ ALL CHECKS PASSED!${NC}"
    echo ""
    echo "Your system is ready to run. Execute:"
    echo ""
    echo "  bash scripts/run_complete_workflow.sh"
    echo ""
elif [ $ERRORS -eq 0 ]; then
    echo -e "${YELLOW}⚠ SYSTEM READY WITH WARNINGS${NC}"
    echo ""
    echo "Warnings: $WARNINGS"
    echo ""
    echo "Your system should work, but some optional components are missing."
    echo "You can proceed with:"
    echo ""
    echo "  bash scripts/run_complete_workflow.sh"
    echo ""
else
    echo -e "${RED}✗ SYSTEM NOT READY${NC}"
    echo ""
    echo "Errors: $ERRORS"
    echo "Warnings: $WARNINGS"
    echo ""
    echo "Please fix the errors above before running the workflow."
    echo ""
fi

# Detailed help
if [ $ERRORS -gt 0 ]; then
    echo "================================================================================"
    echo "FIX INSTRUCTIONS"
    echo "================================================================================"
    echo ""

    # Check if Python packages are the issue
    python3 -c "import datasets" 2>/dev/null || {
        echo "To install missing Python packages:"
        echo ""
        echo "  pip3 install datasets litellm sentence-transformers scikit-learn typer rich numpy"
        echo ""
    }

    # Check if API keys are missing
    if [ -z "$OPENROUTER_API_KEY" ] && [ -z "$MINIMAX_API_KEY" ]; then
        echo "To set API keys (choose one):"
        echo ""
        echo "  # Option 1: OpenRouter"
        echo "  export OPENROUTER_API_KEY='your-key-here'"
        echo "  export OPENROUTER_BASE_URL='https://openrouter.ai/api/v1'"
        echo ""
        echo "  # Option 2: MiniMax"
        echo "  export MINIMAX_API_KEY='your-key-here'"
        echo "  export MINIMAX_BASE_URL='your-base-url'"
        echo ""
        echo "  # Add to ~/.bashrc or ~/.zshrc to persist:"
        echo "  echo 'export OPENROUTER_API_KEY=\"your-key\"' >> ~/.bashrc"
        echo ""
    fi

    # Check if jq is missing
    command -v jq &> /dev/null || {
        echo "To install jq:"
        echo ""
        echo "  # macOS"
        echo "  brew install jq"
        echo ""
        echo "  # Ubuntu/Debian"
        echo "  sudo apt-get install jq"
        echo ""
        echo "  # CentOS/RHEL"
        echo "  sudo yum install jq"
        echo ""
    }
fi

echo "================================================================================"

exit $ERRORS
